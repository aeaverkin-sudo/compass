export const COUNTRIES = new Set(COUNTRY_NAMES.map(foldPlace));
export const CITIES = new Set(CITY_NAMES.map(foldPlace));

const PLACES = new Set([...COUNTRIES, ...CITIES]);

const PLACE_SPLIT = /\s*[,·|/]\s*/;

function isShortPlacePart(part: string) {
  if (!part || part.length > 40) return false;
  return part.split(" ").length <= 4;
}

/** A whole line that is a city, a country, or a short "Lisbon, Portugal". */
export function isPlaceLine(text: string) {
  const folded = foldPlace(text);
  if (!folded) return false;
  if (PLACES.has(folded)) return true;

  const parts = folded.split(PLACE_SPLIT).filter(Boolean);
  if (parts.length >= 2 && parts.length <= 3 && parts.every(isShortPlacePart)) {
    if (parts.every((part) => PLACES.has(part))) return true;
    const last = parts[parts.length - 1] ?? "";
    if (COUNTRIES.has(last)) return true;
    if (COUNTRIES.has(parts[0] ?? "") && CITIES.has(parts[1] ?? "")) return true;
  }

  const words = folded.split(" ");
  if (words.length === 2) {
    const [first, second] = words;
    if (!first || !second) return false;
    if (CITIES.has(first) && COUNTRIES.has(second)) return true;
    if (COUNTRIES.has(first) && CITIES.has(second)) return true;
  }

  return false;
}
