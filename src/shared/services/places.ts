/** Fold a place line so "São Paulo" and "Sao Paulo" match the same key. */
export function foldPlace(text: string) {
  return text
    .trim()
    .toLocaleLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/[.’']/g, "")
    .replace(/\s+/g, " ");
}

